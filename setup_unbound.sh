#!/bin/bash
#-------------------------------------------------------------------------------
#  setup_unbound.sh  -  Unbound recursive DNS for Pi-hole v6 or AdGuard Home
#                       (native OS install)
#
#  Version:       1.1.0
#  Last Updated:  11/5/2026
#  Author:        Christopher Gray
#  Updated by:    Claude Code (Anthropic) - model: Claude Opus 5.5 (claude-opus-5-5)
#
#  What it does (follows https://docs.pi-hole.net/guides/dns/unbound/):
#    1. installs unbound (apt or dnf)
#    2. writes /etc/unbound/unbound.conf.d/pi-hole.conf - listens on 127.0.0.1:5335,
#       validates DNSSEC, DNS-rebinding protection, prefetch
#    3. Debian Bullseye+: disables unbound-resolvconf (it breaks /etc/resolv.conf)
#    4. raises net.core.rmem_max so "so-rcvbuf: 1m" works
#       + enables extended statistics and unbound-control on a local unix socket
#         (/run/unbound.ctl, root only) so mcp_server.py can read the stats
#    5. tests it (pi-hole.net resolves, fail01.dnssec.works is SERVFAIL)
#    6. points your filter at it:
#         Pi-hole v6     -> pihole-FTL --config dns.upstreams '["127.0.0.1#5335"]'
#         AdGuard Home   -> /control/dns_config upstream_dns = 127.0.0.1:5335
#
#  Usage:
#    sudo ./setup_unbound.sh                      # auto-detect Pi-hole / AdGuard Home
#    sudo DNS_FILTER=adguardhome ADGUARD_PASSWORD=xxx ./setup_unbound.sh
#    sudo UNBOUND_IPV6=no ./setup_unbound.sh      # no IPv6 upstream connectivity
#
#  Docker: use install_pihole.sh instead. It runs Unbound (and dnscrypt-proxy) as
#  containers next to Pi-hole or AdGuard Home.
#
#  Settings (env vars or /etc/managed_pihole.conf):
#    DNS_FILTER        auto | pihole | adguardhome | none   (default: auto)
#    UNBOUND_PORT      default 5335
#    UNBOUND_IPV6      yes | no (default yes, as in the Pi-hole guide)
#    ADGUARD_URL / ADGUARD_USER / ADGUARD_PASSWORD   (AdGuard Home only)
#
#  ChangeLog:
#    1.1.0  11/5/2026  (Claude Code) extended-statistics + unbound-control (unix socket,
#                      only if no remote-control is enabled yet) for mcp_server.py.
#    1.0.0  11/5/2026  New file (Claude Code). Native Unbound for Pi-hole and AdGuard Home.
#-------------------------------------------------------------------------------
set -euo pipefail

for _cfg in /etc/managed_pihole.conf "$(dirname "$(readlink -f "$0")")/managed_pihole.conf"; do
    # shellcheck disable=SC1090
    [[ -r "$_cfg" ]] && . "$_cfg"
done

DNS_FILTER="${DNS_FILTER:-auto}"
UNBOUND_PORT="${UNBOUND_PORT:-5335}"
UNBOUND_IPV6="${UNBOUND_IPV6:-yes}"
ADGUARD_URL="${ADGUARD_URL:-http://127.0.0.1}"
ADGUARD_USER="${ADGUARD_USER:-admin}"

[[ $EUID -eq 0 ]] || { echo "Run with sudo."; exit 1; }

if [[ "$DNS_FILTER" == "auto" ]]; then
    if command -v pihole-FTL >/dev/null 2>&1; then DNS_FILTER=pihole
    elif systemctl list-unit-files 2>/dev/null | grep -q '^AdGuardHome'; then DNS_FILTER=adguardhome
    elif docker ps --format '{{.Names}}' 2>/dev/null | grep -qE '^(pihole|adguardhome)$'; then
        echo "A Pi-hole / AdGuard Home container is running. For Docker use install_pihole.sh,"
        echo "which runs Unbound as a container. Set DNS_FILTER=none to install Unbound on the host anyway."
        exit 1
    else DNS_FILTER=none
    fi
fi
echo "Filter to point at Unbound: $DNS_FILTER"

#--- 1. install ---
if command -v apt-get >/dev/null 2>&1; then
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq
    # unbound-anchor is its own package on newer Debian/Ubuntu (creates the DNSSEC root key)
    apt-get install -y -qq unbound unbound-anchor dnsutils >/dev/null 2>&1 \
        || apt-get install -y -qq unbound dnsutils >/dev/null
elif command -v dnf >/dev/null 2>&1; then
    dnf install -y -q unbound bind-utils
else
    echo "Unsupported package manager - install unbound manually, then re-run."; exit 1
fi

#--- 2. config ---
CONF_DIR=/etc/unbound/unbound.conf.d
[[ -d "$CONF_DIR" ]] || CONF_DIR=/etc/unbound/conf.d      # Red Hat family
mkdir -p "$CONF_DIR"
cat > "$CONF_DIR/pi-hole.conf" <<EOF
# Generated by managed_pihole setup_unbound.sh v1.1.0 - https://docs.pi-hole.net/guides/dns/unbound/
server:
    verbosity: 0
    interface: 127.0.0.1
    port: ${UNBOUND_PORT}
    do-ip4: yes
    do-udp: yes
    do-tcp: yes
    do-ip6: ${UNBOUND_IPV6}
    prefer-ip6: no
    harden-glue: yes
    harden-dnssec-stripped: yes
    use-caps-for-id: no
    edns-buffer-size: 1232
    prefetch: yes
    num-threads: 1
    so-rcvbuf: 1m
    private-address: 192.168.0.0/16
    private-address: 169.254.0.0/16
    private-address: 172.16.0.0/12
    private-address: 10.0.0.0/8
    private-address: fd00::/8
    private-address: fe80::/10
    private-address: 192.0.2.0/24
    private-address: 198.51.100.0/24
    private-address: 203.0.113.0/24
    private-address: 255.255.255.255/32
    private-address: 2001:db8::/32
    # rcode / query-type / DNSSEC counters for unbound-control stats (mcp_server.py)
    extended-statistics: yes
EOF

# unbound-control (stats for mcp_server.py). Debian's package may already enable it in
# remote-control.conf; a second control-interface on the same socket would fail to bind.
if ! grep -rqsE '^[[:space:]]*control-enable:[[:space:]]*yes' /etc/unbound --exclude=pi-hole.conf; then
    cat >> "$CONF_DIR/pi-hole.conf" <<'EOF'

remote-control:
    control-enable: yes
    # unix socket: only root (and the unbound user) can talk to it, no TLS keys needed
    control-interface: /run/unbound.ctl
EOF
fi

#--- 3. Debian Bullseye+ resolvconf fix ---
if systemctl is-enabled unbound-resolvconf.service >/dev/null 2>&1; then
    systemctl disable --now unbound-resolvconf.service || true
fi
if [[ -f /etc/resolvconf.conf ]]; then
    sed -Ei 's/^unbound_conf=/#unbound_conf=/' /etc/resolvconf.conf
fi
rm -f "$CONF_DIR/resolvconf_resolvers.conf"

#--- 4. receive buffer ---
echo "net.core.rmem_max=1048576" > /etc/sysctl.d/99-unbound.conf
sysctl -q -w net.core.rmem_max=1048576 || true

#--- DNSSEC trust anchor (normally made by the package's service; make sure it exists) ---
ANCHOR=/var/lib/unbound/root.key
if [[ ! -s "$ANCHOR" ]] && command -v unbound-anchor >/dev/null 2>&1; then
    mkdir -p /var/lib/unbound
    unbound-anchor -a "$ANCHOR" || true      # exit code 1 just means "key was created/updated"
    chown unbound:unbound "$ANCHOR" 2>/dev/null || true
fi
unbound-checkconf >/dev/null || { echo "unbound-checkconf failed:"; unbound-checkconf; exit 1; }

#--- 5. start + test ---
systemctl enable unbound >/dev/null 2>&1 || true
systemctl restart unbound
sleep 2
echo -n "Test pi-hole.net         : "; dig +short pi-hole.net @127.0.0.1 -p "$UNBOUND_PORT" | head -1
echo -n "Test DNSSEC bogus domain : "
if dig fail01.dnssec.works @127.0.0.1 -p "$UNBOUND_PORT" | grep -q SERVFAIL; then echo "SERVFAIL (correct)"; else echo "resolved (DNSSEC NOT working)"; fi

#--- 6. point the filter at Unbound ---
case "$DNS_FILTER" in
  pihole)
    pihole-FTL --config dns.upstreams "[\"127.0.0.1#${UNBOUND_PORT}\"]"
    # Unbound validates DNSSEC; doing it twice only costs time.
    pihole-FTL --config dns.dnssec false
    echo "Pi-hole upstream set to 127.0.0.1#${UNBOUND_PORT}"
    ;;
  adguardhome)
    [[ -n "${ADGUARD_PASSWORD:-}" ]] || { echo "Set ADGUARD_PASSWORD to update AdGuard Home's upstream."; exit 1; }
    curl -fsS -u "${ADGUARD_USER}:${ADGUARD_PASSWORD}" -H 'Content-Type: application/json' \
         -X POST "${ADGUARD_URL%/}/control/dns_config" \
         -d "{\"upstream_dns\":[\"127.0.0.1:${UNBOUND_PORT}\"]}"
    echo "AdGuard Home upstream set to 127.0.0.1:${UNBOUND_PORT}"
    ;;
  *)
    echo "Unbound is ready on 127.0.0.1:${UNBOUND_PORT}. Point your DNS filter's upstream at it."
    ;;
esac
